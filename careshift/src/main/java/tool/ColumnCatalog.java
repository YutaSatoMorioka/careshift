    private ColumnCatalog() {}

    public static boolean isCategory(String s) {
        return CATEGORIES.contains(s);
    }

    /** category が空なら全記事、そうでなければそのカテゴリの記事。 */
    public static List<Article> byCategory(String category) {
        if (category == null || category.isEmpty()) {
            return ALL;
        }
        List<Article> list = new ArrayList<>();
        for (Article a : ALL) {
            if (a.getCategory().equals(category)) list.add(a);
        }
        return list;
    }

    public static Article find(String id) {
        for (Article a : ALL) {
            if (a.getId().equals(id)) return a;
        }
        return null;
    }

    /** ホームでおすすめする記事（日替わりで順に巡る）。 */
    public static Article featured(LocalDate date) {
        return ALL.get(date.getDayOfYear() % ALL.size());
    }
