package dao;

/**
 * テーブル定義。H2 と PostgreSQL の両方で動く標準的なSQLだけで書く。
 * 起動時に Dao が「無ければ作る」(IF NOT EXISTS) ので、テーブルを手で作る必要はない。
 * 画面を実装するたびに、必要なテーブルをここへ追加していく。
 */
final class Schema {

    private Schema() {}

    static final String[] DDL = {
        // S01 / S02 / S03：ユーザー
        "CREATE TABLE IF NOT EXISTS users ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " display_name VARCHAR(30) NOT NULL,"
            + " email VARCHAR(254) NOT NULL UNIQUE,"
            + " password_hash VARCHAR(255) NOT NULL,"
            + " email_verified BOOLEAN NOT NULL DEFAULT FALSE,"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S02 本登録確認 / S03 パスワード再設定：メールのリンク用トークン
        "CREATE TABLE IF NOT EXISTS email_tokens ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " user_id BIGINT NOT NULL REFERENCES users(id),"
            + " purpose VARCHAR(10) NOT NULL,"
            + " token_hash VARCHAR(64) NOT NULL UNIQUE,"
            + " expires_at TIMESTAMP NOT NULL,"
            + " used BOOLEAN NOT NULL DEFAULT FALSE,"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S05：家族グループ
        "CREATE TABLE IF NOT EXISTS family_groups ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " name VARCHAR(30) NOT NULL,"
            + " created_by BIGINT NOT NULL REFERENCES users(id),"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S16：グループのメンバー（1人は1グループにしか所属できない → user_id は UNIQUE）
        // role は PRIMARY（主介護者）/ FAMILY（家族等）
        "CREATE TABLE IF NOT EXISTS group_members ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),"
            + " role VARCHAR(10) NOT NULL,"
            + " relationship VARCHAR(20),"
            + " contact VARCHAR(100),"
            + " joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S04：招待（1名分・7日有効。リンクのトークンはハッシュだけ保存）
        "CREATE TABLE IF NOT EXISTS invitations ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " token_hash VARCHAR(64) NOT NULL UNIQUE,"
            + " relationship VARCHAR(20),"
            + " role VARCHAR(10) NOT NULL,"
            + " invited_by BIGINT NOT NULL REFERENCES users(id),"
            + " expires_at TIMESTAMP NOT NULL,"
            + " used_by BIGINT REFERENCES users(id),"
            + " used_at TIMESTAMP,"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // NOTI001：通知
        "CREATE TABLE IF NOT EXISTS notifications ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " user_id BIGINT NOT NULL REFERENCES users(id),"
            + " type VARCHAR(10) NOT NULL,"
            + " message VARCHAR(200) NOT NULL,"
            + " link_path VARCHAR(200),"
            + " is_read BOOLEAN NOT NULL DEFAULT FALSE,"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // タスク管理
        "CREATE TABLE IF NOT EXISTS care_tasks ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " title VARCHAR(100) NOT NULL, details VARCHAR(1000), due_at TIMESTAMP NOT NULL,"
            + " duration_minutes INTEGER NOT NULL, frequency VARCHAR(30),"
            + " assignee_user_id BIGINT REFERENCES users(id), status VARCHAR(12) NOT NULL DEFAULT 'TODO',"
            + " created_by BIGINT NOT NULL REFERENCES users(id),"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
            + " updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",
        "CREATE TABLE IF NOT EXISTS care_requests ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " requester_id BIGINT NOT NULL REFERENCES users(id), type VARCHAR(10) NOT NULL,"
            + " title VARCHAR(100) NOT NULL, body VARCHAR(1000), requested_at TIMESTAMP,"
            + " duration_minutes INTEGER, status VARCHAR(12) NOT NULL DEFAULT 'OPEN',"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",
        "CREATE TABLE IF NOT EXISTS care_request_responses ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " request_id BIGINT NOT NULL REFERENCES care_requests(id),"
            + " responder_id BIGINT NOT NULL REFERENCES users(id), choice VARCHAR(20) NOT NULL,"
            + " message VARCHAR(500), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
            + " UNIQUE(request_id, responder_id)"
            + ")",
        "CREATE TABLE IF NOT EXISTS rest_records ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " user_id BIGINT NOT NULL REFERENCES users(id), starts_at TIMESTAMP NOT NULL,"
            + " ends_at TIMESTAMP NOT NULL, note VARCHAR(300), status VARCHAR(12) NOT NULL DEFAULT 'REQUESTED',"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",
        "CREATE TABLE IF NOT EXISTS task_reminders ("
            + " task_id BIGINT NOT NULL REFERENCES care_tasks(id), reminder_date DATE NOT NULL,"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(task_id, reminder_date)"
            + ")",
        "CREATE TABLE IF NOT EXISTS group_plans ("
            + " group_id BIGINT PRIMARY KEY REFERENCES family_groups(id), plan_name VARCHAR(20) NOT NULL DEFAULT '無料',"
            + " starts_at DATE NOT NULL DEFAULT CURRENT_DATE, ends_at DATE"
            + ")",
        "CREATE TABLE IF NOT EXISTS operation_logs ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, level VARCHAR(10) NOT NULL,"
            + " screen VARCHAR(100), message VARCHAR(500) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",
        "CREATE TABLE IF NOT EXISTS care_alerts ("
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " user_id BIGINT NOT NULL REFERENCES users(id), alert_date DATE NOT NULL,"
            + " PRIMARY KEY(group_id,user_id,alert_date)"
            + ")",
        "CREATE TABLE IF NOT EXISTS care_check_items ("
            + " user_id BIGINT NOT NULL REFERENCES users(id), item_key VARCHAR(40) NOT NULL,"
            + " checked BOOLEAN NOT NULL DEFAULT FALSE, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
            + " PRIMARY KEY(user_id,item_key)"
            + ")"
    };
}
