package dao;

/**
 * テーブル定義。H2 と PostgreSQL の両方で動く標準的なSQLだけで書く。
 * 起動時に Dao が「無ければ作る」(IF NOT EXISTS) ので、テーブルを手で作る必要はない。
 * 画面を実装するたびに、必要なテーブルをここへ追加していく。
 */
final class Schema {

    private Schema() {}

    static final String[] DDL = {
        // S01 / S02 / S03：ユーザー
        "CREATE TABLE IF NOT EXISTS users ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " display_name VARCHAR(30) NOT NULL,"
            + " email VARCHAR(254) NOT NULL UNIQUE,"
            + " password_hash VARCHAR(255) NOT NULL,"
            + " email_verified BOOLEAN NOT NULL DEFAULT FALSE,"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S02 本登録確認 / S03 パスワード再設定：メールのリンク用トークン
        "CREATE TABLE IF NOT EXISTS email_tokens ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " user_id BIGINT NOT NULL REFERENCES users(id),"
            + " purpose VARCHAR(10) NOT NULL,"
            + " token_hash VARCHAR(64) NOT NULL UNIQUE,"
            + " expires_at TIMESTAMP NOT NULL,"
            + " used BOOLEAN NOT NULL DEFAULT FALSE,"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S05：家族グループ
        "CREATE TABLE IF NOT EXISTS family_groups ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " name VARCHAR(30) NOT NULL,"
            + " created_by BIGINT NOT NULL REFERENCES users(id),"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S16：グループのメンバー（1人は1グループにしか所属できない → user_id は UNIQUE）
        // role は PRIMARY（主介護者）/ FAMILY（家族等）
        "CREATE TABLE IF NOT EXISTS group_members ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),"
            + " role VARCHAR(10) NOT NULL,"
            + " relationship VARCHAR(20),"
            + " contact VARCHAR(100),"
            + " joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S04：招待（1名分・7日有効。リンクのトークンはハッシュだけ保存）
        "CREATE TABLE IF NOT EXISTS invitations ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " token_hash VARCHAR(64) NOT NULL UNIQUE,"
            + " relationship VARCHAR(20),"
            + " role VARCHAR(10) NOT NULL,"
            + " invited_by BIGINT NOT NULL REFERENCES users(id),"
            + " expires_at TIMESTAMP NOT NULL,"
            + " used_by BIGINT REFERENCES users(id),"
            + " used_at TIMESTAMP,"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // NOTI001：通知（参加通知などをここに積む。一覧画面は後で実装）
        "CREATE TABLE IF NOT EXISTS notifications ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " user_id BIGINT NOT NULL REFERENCES users(id),"
            + " type VARCHAR(10) NOT NULL,"
            + " message VARCHAR(200) NOT NULL,"
            + " link_path VARCHAR(200),"
            + " is_read BOOLEAN NOT NULL DEFAULT FALSE,"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S07〜S10：タスク。status は TODO/DOING/DONE、frequency は ONCE/DAILY/WEEKLY/MONTHLY。
        // lock_version は「先に誰かが更新した」ことを検知する印（更新のたびに +1。競合時は最新を再読込）
        "CREATE TABLE IF NOT EXISTS tasks ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " title VARCHAR(100) NOT NULL,"
            + " due_date DATE NOT NULL,"
            + " duration_min INTEGER NOT NULL,"
            + " frequency VARCHAR(10) NOT NULL DEFAULT 'ONCE',"
            + " assignee_id BIGINT REFERENCES users(id),"
            + " status VARCHAR(10) NOT NULL DEFAULT 'TODO',"
            + " created_by BIGINT NOT NULL REFERENCES users(id),"
            + " lock_version INTEGER NOT NULL DEFAULT 0,"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
            + " updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S14：休息予定。status は ADJUSTING（調整中）/ CONFIRMED（確定）/ CANCELLED（取消）。
        // 休息を保証するものではなく、家族との調整を始める予定として扱う。
        "CREATE TABLE IF NOT EXISTS rest_plans ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " rest_date DATE NOT NULL,"
            + " start_time TIME NOT NULL,"
            + " end_time TIME NOT NULL,"
            + " content VARCHAR(300) NOT NULL,"
            + " status VARCHAR(10) NOT NULL DEFAULT 'ADJUSTING',"
            + " created_by BIGINT NOT NULL REFERENCES users(id),"
            + " covered_by BIGINT REFERENCES users(id),"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
            + " updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // S11〜S13：依頼カード。type は TASK / REST、status は OPEN / ACCEPTED / WITHDRAWN。
        // 期限切れは「status が OPEN のまま requested_at を過ぎた」状態として画面側で判定する。
        // task_id のタスクが削除されても依頼は残す（ON DELETE SET NULL）。
        "CREATE TABLE IF NOT EXISTS requests ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " group_id BIGINT NOT NULL REFERENCES family_groups(id),"
            + " type VARCHAR(10) NOT NULL,"
            + " content VARCHAR(500) NOT NULL,"
            + " requested_at TIMESTAMP NOT NULL,"
            + " duration_min INTEGER,"
            + " task_id BIGINT REFERENCES tasks(id) ON DELETE SET NULL,"
            + " rest_id BIGINT REFERENCES rest_plans(id),"
            + " sender_id BIGINT NOT NULL REFERENCES users(id),"
            + " status VARCHAR(10) NOT NULL DEFAULT 'OPEN',"
            + " accepted_by BIGINT REFERENCES users(id),"
            + " created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,"
            + " updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
            + ")",

        // 依頼の宛先ごとの回答。response は ACCEPT / DECLINE / ALT（未回答は NULL）
        "CREATE TABLE IF NOT EXISTS request_recipients ("
            + " request_id BIGINT NOT NULL REFERENCES requests(id),"
            + " user_id BIGINT NOT NULL REFERENCES users(id),"
            + " response VARCHAR(10),"
            + " alternative VARCHAR(300),"
            + " responded_at TIMESTAMP,"
            + " PRIMARY KEY (request_id, user_id)"
            + ")",

        // ---- ここから下は、すでにテーブルがある既存のDBにも反映される形（ALTER / IF NOT EXISTS）で追加する ----

        // NOTI001：期限リマインドなど「同じ通知を二重に作らない」ための識別キー（通常の通知は NULL）
        "ALTER TABLE notifications ADD COLUMN IF NOT EXISTS ref_key VARCHAR(100)",
        "CREATE UNIQUE INDEX IF NOT EXISTS ux_notifications_ref ON notifications (user_id, ref_key)",

        // S20：通知設定（行がなければ初期値：メール通知オフ・期限リマインドオン）
        "CREATE TABLE IF NOT EXISTS user_settings ("
            + " user_id BIGINT NOT NULL PRIMARY KEY REFERENCES users(id),"
            + " email_notice BOOLEAN NOT NULL DEFAULT FALSE,"
            + " reminder BOOLEAN NOT NULL DEFAULT TRUE"
            + ")",

        // S18：コラムのチェックリストの状態。利用者個人にだけ保存し、家族とは共有しない。
        // 行があれば「チェック済み」（item_index は項目の番号）
        "CREATE TABLE IF NOT EXISTS checklist_states ("
            + " user_id BIGINT NOT NULL REFERENCES users(id),"
            + " article_id VARCHAR(40) NOT NULL,"
            + " item_index INTEGER NOT NULL,"
            + " PRIMARY KEY (user_id, article_id, item_index)"
            + ")"
    };
}
